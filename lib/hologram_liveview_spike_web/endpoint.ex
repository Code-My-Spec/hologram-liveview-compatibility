defmodule HologramLiveviewSpikeWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :hologram_liveview_spike

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_hologram_liveview_spike_key",
    signing_salt: "1E0kwkVN",
    same_site: "Lax"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :hologram_liveview_spike,
    gzip: not code_reloading?,
    only: HologramLiveviewSpikeWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  # Answered here, above everything else, because the claim is that health
  # does not depend on the database. In dev `Phoenix.Ecto.CheckRepoStatus`
  # sits between the endpoint and the router and answers 503 when the
  # database is absent — so a health route in the router is unreachable
  # exactly when a probe most wants an answer, and the deploy proxy reads
  # that 503 as an unhealthy container.
  plug :health_check

  defp health_check(%Plug.Conn{request_path: "/health"} = conn, _opts) do
    conn
    |> Plug.Conn.send_resp(200, "ok")
    |> Plug.Conn.halt()
  end

  defp health_check(conn, _opts), do: conn

  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :hologram_liveview_spike
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    # The Resend webhook verifies a signature over the exact bytes sent, and
    # Plug.Parsers has already consumed them by the time a controller runs.
    # `CacheBodyReader` stashes the raw body for `/webhooks/` requests only,
    # so it costs nothing on the routes that don't need it.
    body_reader: {HologramLiveviewSpikeWeb.CacheBodyReader, :read_body, []},
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug Hologram.Router
  plug HologramLiveviewSpikeWeb.Router
end
